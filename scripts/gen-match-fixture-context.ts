/**
 * Builds `tests/fixtures/match-golden-context.json`: the twenty bodies of `match-golden.json`, each with the match
 * context the app builds for it (review 2026-11-07 §3.3, plan 2.3).
 *
 * The first fixture matches with no context, so the gates that read one (host and colour star, the measured
 * exclusions keyed on host, main star and region, orbit, arrival distance, region, companion bodies, starlight) are
 * pinned by nothing fast. This one stores the context `buildSpeciesMatchContextFromRecords` gives each body from the
 * journal merge cache (derived values only, not the system's raw records), the body's signal count, and both tiers
 * with each row's presence factor; `tests/matchGoldenContext.test.ts` re-matches them on every run.
 *
 *   EDEXO_USER_DATA_DIR=<dir with a journal merge cache> npx tsx scripts/gen-match-fixture-context.ts
 *
 * Re-run it deliberately when a change is meant to move predictions, and review the diff.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import v8 from "node:v8";
import { gunzipSync } from "node:zlib";
import { loadSpeciesDatabaseFromTree } from "../src/server/speciesTreeLoader.js";
import { matchDatabaseToScan } from "../src/server/matchSpecies.js";
import { decodeJournalMergeCache } from "../src/server/journalMergeCacheEncoding.js";
import { journalMergeCachePath, probeMatchContexts } from "./probeCache.js";
import type { PlanetScan } from "../src/shared/types.js";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const db = loadSpeciesDatabaseFromTree(root);

/*
  Read without the probes' format check: the context comes from the bodies and exploration records, which no format
  bump since 42 changed, and an older cache saves a full replay of the journals. The format is written into the
  fixture so a reader knows what it came from.
*/
const cachePath = journalMergeCachePath();
if (!existsSync(cachePath)) {
  console.error(`No journal merge cache at ${cachePath}.`);
  process.exit(1);
}
const raw = readFileSync(cachePath);
const payload = decodeJournalMergeCache(
  raw[0] === 0x1f && raw[1] === 0x8b ? v8.deserialize(gunzipSync(raw)) : JSON.parse(raw.toString("utf8")),
);
if (!payload) {
  console.error(`Cache at ${cachePath} did not decode.`);
  process.exit(1);
}
const { contextFor } = probeMatchContexts(payload);

const first = JSON.parse(readFileSync(path.join(root, "tests", "fixtures", "match-golden.json"), "utf8")) as {
  cases: { bodyName: string; scan: Record<string, unknown>; confirmedSpecies: string[] }[];
};
/*
  The first fixture's names are often the cache's placeholder ("Body 62", a body known before its Scan), so a body is
  found by its scan: class, temperature, gravity and pressure as the fixture stored them.
*/
const sameScan = (a: Record<string, unknown>, s: PlanetScan | null | undefined) =>
  !!s &&
  ["PlanetClass", "SurfaceTemperature", "SurfaceGravity", "SurfacePressure"].every(
    (k) => a[k] === (s as unknown as Record<string, unknown>)[k],
  );

const cases = first.cases.map((c) => {
  const found = payload.bodies.filter(([, b]) => sameScan(c.scan, b.scan));
  if (found.length !== 1) throw new Error(`${c.bodyName}: ${found.length} bodies in the cache have its scan`);
  const b = found[0]![1];
  const context = JSON.parse(JSON.stringify(contextFor(b) ?? null)) as Record<string, unknown> | null;
  const biologicalSignals = b.biologicalSignals ?? null;
  const matches = matchDatabaseToScan(db, c.scan as unknown as PlanetScan, null, null, {
    includeBacterium: true,
    matchContext: context as never,
    biologicalSignals,
  }).matches;
  const row = (m: (typeof matches)[number]) =>
    m.presenceFactor != null && m.presenceFactor !== 1 ? `${m.entry.id} x${m.presenceFactor.toFixed(4)}` : m.entry.id;
  return {
    bodyName: c.bodyName,
    scan: c.scan,
    confirmedSpecies: c.confirmedSpecies,
    biologicalSignals,
    context,
    candidates: matches.filter((m) => !m.unlikely).map(row).sort(),
    unlikely: matches.filter((m) => m.unlikely).map(row).sort(),
  };
});

const fixture = {
  note: "Generated by scripts/gen-match-fixture-context.ts: match-golden.json's bodies with their match context. Regenerate deliberately.",
  generatedAt: new Date().toISOString().slice(0, 10),
  cacheFormat: payload.format,
  cases,
};
const outPath = path.join(root, "tests", "fixtures", "match-golden-context.json");
writeFileSync(outPath, `${JSON.stringify(fixture, null, 2)}\n`, "utf8");
const shown = cases.reduce((n, c) => n + c.candidates.length, 0);
const unlikely = cases.reduce((n, c) => n + c.unlikely.length, 0);
const withCtx = cases.filter((c) => c.context).length;
console.log(`wrote ${outPath}: ${cases.length} bodies (${withCtx} with a context), ${shown} shown + ${unlikely} unlikely rows`);
