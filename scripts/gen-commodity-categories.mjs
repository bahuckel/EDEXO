/**
 * Generates `src/shared/colonize/commodityCategoryLookup.gen.ts` and `commoditySpanshSlugs.gen.ts` from EDCD FDevIDs
 * commodity.csv (scripts/commodity.fdevids.csv, or a path given). Brought over from the EDEXO-Colonize repo with the
 * tables it writes (discuss item 31, owner 2026-10-23).
 * Run: node scripts/gen-commodity-categories.mjs [path/to/commodity.csv]
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const csvPath = process.argv[2] || join(__dirname, "commodity.fdevids.csv");
const outPath = join(root, "src", "shared", "colonize", "commodityCategoryLookup.gen.ts");
const spanshSlugsOutPath = join(root, "src", "shared", "colonize", "commoditySpanshSlugs.gen.ts");

function normKey(s) {
  return s
    .normalize("NFKD")
    .replace(/\p{M}/gu, "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

/** Preferred UI order (remaining categories appended alphabetically at build time). */
const BASE_ORDER = [
  "Metals",
  "Minerals",
  "Chemicals",
  "Industrial Materials",
  "Foods",
  "Textiles",
  "Medicines",
  "Legal Drugs",
  "Machinery",
  "Technology",
  "Weapons",
  "Consumer Items",
  "Waste",
  "Slavery",
  "Salvage",
  "NonMarketable",
];

function readCsvText(p) {
  const buf = readFileSync(p);
  if (buf.length >= 2 && buf[0] === 0xff && buf[1] === 0xfe) {
    return buf.subarray(2).toString("utf16le");
  }
  if (buf.length >= 2 && buf[0] === 0xfe && buf[1] === 0xff) {
    return Buffer.from(buf.subarray(2)).swap16().toString("utf16le");
  }
  let s = buf.toString("utf8");
  if (s.charCodeAt(0) === 0xfeff) s = s.slice(1);
  return s;
}

function titleCaseWords(s) {
  return s
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1).toLowerCase())
    .join(" ");
}

function main() {
  let raw = readCsvText(csvPath);
  const fileLines = raw.split(/\r?\n/);
  let header = true;
  const lookup = Object.create(null);
  const categories = new Set();
  /** @type {Record<string, string[]>} */
  const slugByNorm = Object.create(null);
  /** FDev numeric id → shortest norm key from that row (Cargo / odd journal sources sometimes use id as `Name`). */
  const fidToMergeKey = Object.create(null);

  for (const line of fileLines) {
    const t = line.trim();
    if (!t) continue;
    if (header) {
      header = false;
      continue;
    }
    const m = /^(\d+),([^,]+),([^,]+),(.+)$/.exec(t);
    if (!m) continue;
    const category = m[3].trim();
    const symbol = m[2].trim();
    const name = m[4].trim();
    categories.add(category);
    const keys = new Set();
    keys.add(normKey(symbol));
    keys.add(normKey(name));
    if (name.includes(" ")) keys.add(normKey(name.replace(/\s+/g, "")));
    for (const k of keys) {
      if (k) lookup[k] = category;
    }

    const slugOrdered = [];
    const seenSlug = new Set();
    const pushSlug = (s) => {
      const z = typeof s === "string" ? s.trim() : "";
      if (!z || seenSlug.has(z)) return;
      seenSlug.add(z);
      slugOrdered.push(z);
    };
    pushSlug(name);
    pushSlug(symbol);
    const titled = titleCaseWords(name);
    if (titled !== name) pushSlug(titled);

    for (const k of keys) {
      if (!k) continue;
      let cur = slugByNorm[k];
      if (!cur) cur = [];
      for (const s of slugOrdered) {
        if (!cur.includes(s)) cur.push(s);
      }
      slugByNorm[k] = cur;
    }

    const nkCand = [...keys].filter(Boolean).sort((a, b) => (a.length !== b.length ? a.length - b.length : a.localeCompare(b)));
    if (nkCand.length) fidToMergeKey[String(m[1].trim())] = nkCand[0];
  }

  /**
   * Reverse of `slugByNorm`, keyed by the *normalised* slug. Without it the runtime has to walk every
   * catalogue row and re-normalise every slug on each `commodityCatalogNormKeys` call; emitting it here
   * turns that scan into a hash lookup. Insertion order mirrors `slugByNorm`, which callers rely on for
   * the order of the keys they get back.
   */
  const normKeysBySlugNorm = Object.create(null);
  for (const [nk, slugs] of Object.entries(slugByNorm)) {
    for (const slug of slugs) {
      const sn = normKey(slug);
      let arr = normKeysBySlugNorm[sn];
      if (!arr) {
        arr = [];
        normKeysBySlugNorm[sn] = arr;
      }
      if (!arr.includes(nk)) arr.push(nk);
    }
  }

  const rest = [...categories].filter((c) => !BASE_ORDER.includes(c)).sort((a, b) => a.localeCompare(b));
  const fullOrder = [...BASE_ORDER.filter((c) => categories.has(c)), ...rest, "Other"];

  const outLines = [
    "/** AUTO-GENERATED by scripts/gen-commodity-categories.mjs — do not edit. */",
    "",
    `export const COMMODITY_CATEGORY_DISPLAY_ORDER: string[] = ${JSON.stringify(fullOrder, null, 2)};`,
    "",
    "/** Normalised keys (symbol + display name) → Frontier trade category from FDevIDs/commodity.csv */",
    `export const COMMODITY_CATEGORY_BY_NORM_KEY: Record<string, string> = ${JSON.stringify(lookup, null, 2)};`,
    "",
  ];

  writeFileSync(outPath, outLines.join("\n"), "utf8");
  console.log(`Wrote ${outPath} (${Object.keys(lookup).length} keys, ${categories.size} categories)`);

  const spanshLines = [
    "/** AUTO-GENERATED by scripts/gen-commodity-categories.mjs — Spansh /commodity/buy slug hints from FDevIDs name + symbol (try first). */",
    "",
    `export const COMMODITY_SPANSH_SLUGS_BY_NORM_KEY: Record<string, string[]> = ${JSON.stringify(slugByNorm, null, 2)};`,
    "",
    "/** Cargo sometimes reports `Name` as the numeric FDev id — normalize to merge keys used elsewhere */",
    `export const COMMODITY_FDEV_ID_TO_MERGE_KEY: Record<string, string> = ${JSON.stringify(fidToMergeKey, null, 2)};`,
    "",
    "/** Reverse index of the slugs above, keyed by normalised slug, so lookups need no catalogue scan. */",
    `export const COMMODITY_NORM_KEYS_BY_SLUG_NORM: Record<string, string[]> = ${JSON.stringify(normKeysBySlugNorm, null, 2)};`,
    "",
  ];
  writeFileSync(spanshSlugsOutPath, spanshLines.join("\n"), "utf8");
  console.log(`Wrote ${spanshSlugsOutPath} (${Object.keys(slugByNorm).length} norm keys)`);
}

main();
